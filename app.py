import os
import math

import psycopg
from psycopg.rows import dict_row
from datetime import datetime, timedelta, timezone

from flask import Flask, jsonify, request
from flask_cors import CORS


app = Flask(__name__)
CORS(app)

DATABASE_URL = os.environ.get("DATABASE_URL", "")
KST = timezone(timedelta(hours=9))

QUIET_MAX_DB = 45.0
NORMAL_MAX_DB = 65.0


def get_db():
    if not DATABASE_URL:
        raise RuntimeError("Render의 환경변수 DATABASE_URL을 설정해 주세요.")
    return psycopg.connect(
        DATABASE_URL, row_factory=dict_row, connect_timeout=15,
        options="-c statement_timeout=15000",
    )


def init_db():
    with get_db() as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS readings (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                device_id TEXT NOT NULL,
                location_id TEXT NOT NULL,
                location_name TEXT NOT NULL,
                db DOUBLE PRECISION NOT NULL,
                lux DOUBLE PRECISION,
                temperature DOUBLE PRECISION,
                humidity DOUBLE PRECISION,
                recorded_at TIMESTAMPTZ NOT NULL
            )
            """
        )
        conn.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_location_time
            ON readings(location_id, recorded_at)
            """
        )


def get_status(db):
    if db < QUIET_MAX_DB:
        return "quiet"
    if db < NORMAL_MAX_DB:
        return "normal"
    return "loud"


def row_to_dict(row):
    result = dict(row)
    result["recorded_at"] = result["recorded_at"].astimezone(KST).isoformat(timespec="seconds")
    result["status"] = get_status(result["db"])
    return result


